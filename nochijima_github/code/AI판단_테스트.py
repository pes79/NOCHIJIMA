def _items(rows):
    return [{"country": c, "ko": t, "title": "", "src_name": "", "pub": "", "guid": f"t{i}"}
            for i, (c, t, _, _) in enumerate(rows)]


def list_models(cfg):
    req = Request("https://generativelanguage.googleapis.com/v1beta/models?pageSize=200",
                  headers={"x-goog-api-key": cfg["api_key"]})
    data = json.loads(urlopen(req, timeout=30).read().decode("utf-8"))
    names = [m["name"].split("/")[-1] for m in data.get("models", [])
             if "generateContent" in m.get("supportedGenerationMethods", [])]
    return [n for n in names if "flash" in n or "lite" in n]


def run(cfg, label):
    print(f"\n######## 모델: {label} ########")
    total_ok = total = 0
    for kind, rows in (("대형사고", INCIDENT), ("정책", POLICY)):
        _, res = ai.judge(kind, _items(rows), cfg=cfg, use_pending=False,
                          hold_on_fail=False, write_log=False)
        print(f"\n| {kind} | 나라 | 기사 | 기대 | AI | 맞음 | AI 이유 |")
        print("|---|---|---|---|---|---|---|")
        for i, (c, t, exp, memo) in enumerate(rows):
            ans, why = res.get(f"t{i}", ("?", ""))
            ok = "✅" if ans == exp else ("⏸" if ans == "보류" else "❌")
            total += 1
            total_ok += ans == exp
            print(f"| {memo} | {c} | {t[:38]} | {exp} | {ans} | {ok} | {why} |")
    items = [{"country": c, "ko": t, "title": "", "src_name": "", "pub": "", "guid": f"d{i}"} for i, (c, t) in enumerate(DUP)]
    passed, res = ai.judge("정책", items, cfg=cfg, use_pending=False, hold_on_fail=False, write_log=False)
    good = len(passed) == 1
    total += 1
    total_ok += good
    print(f"\n같은 소식 {len(DUP)}건 → 통과 {len(passed)}건 {'✅' if good else '❌'}"
          + "".join(f"\n   - {res[it['guid']][0]}: {(it.get('ai') or {}).get('summary') or res[it['guid']][1]}" for it in items))
    print(f"\n→ 정답 {total_ok}/{total}")
    return total_ok, total


def main():
    cfg = ai.load_config()
    if not cfg.get("api_key"):
        print("❌ gemini_config.json 에 API 키가 아직 없습니다. (키 넣는 법은 AI판단.py 맨 위 설명 참고)")
        return
    arg = sys.argv[1] if len(sys.argv) > 1 else ""
    if arg == "모델":
        print("\n".join(list_models(cfg)))
        return
    models = cfg.get("models") or ai.DEFAULT_MODELS
    if arg == "비교":
        score = {}
        for m in models:
            c = dict(cfg, models=[m])
            score[m] = run(c, m)
        print("\n== 모델별 정답 ==")
        for m, (a, b) in score.items():
            print(f"  {m}: {a}/{b}")
    else:
        run(cfg, " → ".join(models) + " (앞에서부터)")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    main()
